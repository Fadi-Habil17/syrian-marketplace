export function assertTransition(from: OrderState, to: OrderState) {
  if (from === to) return;
  if (!graph[from]?.includes(to)) fail('INVALID_TRANSITION');
}
export function beforeDeadline(now: Date, deadline: Date | null) {
  if (!deadline || now >= deadline) fail('DEADLINE_EXPIRED');
}
