export function readable(value: string) {
  if (value === value.toUpperCase())
    return value
      .replaceAll('_', ' ')
      .toLowerCase()
      .replace(/^./, (char) => char.toUpperCase());
  return value.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (char) => char.toUpperCase());
}

export function field(locale: Locale, name: string) {
  return choose(locale, fields[name] ?? readable(name), readable(name));
}

export function enumLabel(locale: Locale, value: string) {
  return choose(locale, values[value] ?? readable(value), readable(value));
}

export function actionLabel(locale: Locale, name: string) {
  const labels = actions[name];
  return labels ? choose(locale, ...labels) : field(locale, name);
}

